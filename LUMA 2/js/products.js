
document.addEventListener("DOMContentLoaded", () => {
  const form = document.querySelector("#plant-search-form");
  const input = document.querySelector("#plant-search-input");
  const grid = document.querySelector(".product-grid");
  const status = document.querySelector("#products-status");

  if (!form || !input || !grid || !status) return;

  // Keep original cards so we can restore them
  const originalHTML = grid.innerHTML;


  function renderProducts(products) {
    grid.replaceChildren();

    if (products.length === 0) {
      const message = document.createElement("p");
      message.textContent = "No plants found.";
      grid.appendChild(message);
      return;
    }

    products.forEach((plant) => {
      const card = document.createElement("article");
      card.className = "product-card";

      const link = document.createElement("a");
      link.className = "product-image";
      link.href = "product.php?id=" + encodeURIComponent(plant.id);
      link.setAttribute("aria-label", "View " + plant.name);

      const img = document.createElement("img");
      img.src = "images/" + encodeURIComponent(plant.thumbnail) + "?v=4";
      img.alt = plant.name;
      img.className = "plant-photo";

      const more = document.createElement("span");
      more.className = "more-details";
      more.textContent = "MORE DETAILS";
      link.append(img, more);

      const name = document.createElement("h3");
      name.textContent = plant.name;

      const price = document.createElement("p");
      price.className = "product-price";
      price.textContent = "$" + Number(plant.price).toFixed(2);

      const category = document.createElement("span");
      category.className = "care-badge";
      category.textContent = plant.category;

      card.append(link, name, price, category);
      grid.appendChild(card);
    });
  }



  // Module 12: Filter categories using API
  const categoryLinks = document.querySelectorAll(
    ".filter-card a"
  );

  categoryLinks.forEach((link) => {
    link.addEventListener("click", async (event) => {
      event.preventDefault();

      const linkUrl = new URL(link.href);
      const category =
        linkUrl.searchParams.get("category") || "All";

      // Clear search when selecting a category
      input.value = "";
      status.textContent = "LOADING...";

      try {
        const url =
          "api.php?type=product_filter&category="
          + encodeURIComponent(category);

        const response = await fetch(url);

        if (!response.ok) {
          throw new Error("Filter request failed");
        }

        const products = await response.json();

        // Keep cards matching the selected category
        const matchingIds = new Set(
          products.map((plant) => String(plant.id))
        );

        // Request all products and rebuild matching cards
        const allResponse = await fetch(
          "api.php?type=products_all"
        );

        if (!allResponse.ok) {
          throw new Error("Unable to load products");
        }

        const allProducts = await allResponse.json();

        // Use the same product cards generated by Search
        input.value = category === "All" ? "" : input.value;

        // Update the page through a fresh request
        const searchForm = document.querySelector(
          "#plant-search-form"
        );

        grid.innerHTML = originalHTML;

        grid.querySelectorAll(".product-card").forEach(
          (card) => {
            const productLink = card.querySelector(
              'a[href*="product.php?id="]'
            );

            if (!productLink) return;

            const id = new URL(
              productLink.href
            ).searchParams.get("id");

            if (!matchingIds.has(String(id))) {
              card.remove();
            }
          }
        );

        status.textContent = "SHOWING: " + category;

      } catch (error) {
        console.error(error);
        status.textContent = "FILTER FAILED";
      }
    });
  });






  form.addEventListener("submit", async (event) => {
    event.preventDefault();

    const search = input.value.trim();

    // Empty search: show original products
    if (search === "") {
      grid.innerHTML = originalHTML;
      status.textContent = "SHOWING: All";
      return;
    }

    status.textContent = "SEARCHING...";

    try {
      const url = "api.php?type=product_search&search="
        + encodeURIComponent(search);

      const response = await fetch(url);

      if (!response.ok) {
        throw new Error("Search request failed");
      }

      const products = await response.json();

      grid.replaceChildren();

      if (products.length === 0) {
        status.textContent = "NO RESULTS";
        const message = document.createElement("p");
        message.textContent = "No plants found. Try another name.";
        grid.appendChild(message);
        return;
      }

      products.forEach((plant) => {
        const card = document.createElement("article");
        card.className = "product-card";

        const link = document.createElement("a");
        link.className = "product-image";
        link.href = "product.php?id=" + encodeURIComponent(plant.id);
        link.setAttribute("aria-label", "View " + plant.name);

        const img = document.createElement("img");
        img.src = "images/" + encodeURIComponent(plant.thumbnail) + "?v=4";
        img.alt = plant.name;
        img.className = "plant-photo";

        const more = document.createElement("span");
        more.className = "more-details";
        more.textContent = "MORE DETAILS";

        link.append(img, more);

        const name = document.createElement("h3");
        name.textContent = plant.name;

        const price = document.createElement("p");
        price.className = "product-price";
        price.textContent = "$" + Number(plant.price).toFixed(2);

        const category = document.createElement("span");
        category.className = "care-badge";
        category.textContent = plant.category;

        card.append(link, name, price, category);
        grid.appendChild(card);
      });

      status.textContent = "SEARCH RESULTS: " + products.length;

    } catch (error) {
      console.error(error);
      grid.innerHTML = originalHTML;
      status.textContent = "SEARCH FAILED";
    }
  });
  
  // Module 12: Sort products
  const sortSelect = document.querySelector("#plant-sort-select");

  if (sortSelect) {
    sortSelect.addEventListener("change", async () => {
      const sort = sortSelect.value;

      // Reset search when sorting
      input.value = "";

      if (sort === "") {
        grid.innerHTML = originalHTML;
        status.textContent = "SHOWING: All";
        return;
      }

      status.textContent = "SORTING...";

      try {
        const url = "api.php?type=product_sort&sort="
          + encodeURIComponent(sort);

        const response = await fetch(url);

        if (!response.ok) {
          throw new Error("Sort request failed");
        }

        const products = await response.json();

        renderProducts(products);
        status.textContent = "SORTED: " +
          sortSelect.options[sortSelect.selectedIndex].text;

      } catch (error) {
        console.error(error);
        status.textContent = "SORT FAILED";
      }
    });
  }

});
